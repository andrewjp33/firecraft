//! Fireworks' stroke presets (the Property inspector's stroke categories), with every brush
//! setting, from FirePixel's `fp-engine/src/commands/panel.rs` (`BRUSH_PRESETS`, Apache-2.0) and
//! the English names from its `fp-i18n` en locale. `category`/`name` are the file's `CATs`/`INMs`.
//!
//! Sensitivities are Fireworks MX's own, read back from each stock stroke through its scripting
//! API (FirePixel's table lacked every Horizontal and Vertical source and Lightness target).

use firecraft_fwpng::Node;

