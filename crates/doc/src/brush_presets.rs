/// The preset with this category and name (`CATs`/`INMs`).
pub fn find(category: &str, name: &str) -> Option<usize> {
    BRUSH_PRESETS.iter().position(|p| p.category == category && p.name == name)
}

/// A preset's English name.
pub fn label(p: &BrushPreset) -> String {
    PRESET_LABELS
        .iter()
        .find(|(c, n, _)| *c == p.category && *n == p.name)
        .map_or_else(|| p.name.trim_start_matches("bn_").to_owned(), |(_, _, l)| (*l).to_owned())
}

/// A category's English name.
pub fn category_label(category: &str) -> String {
    CATEGORY_LABELS
        .iter()
        .find(|(c, _)| *c == category)
        .map_or_else(|| category.trim_start_matches("bc_").to_owned(), |(_, l)| (*l).to_owned())
}

/// The label the Property inspector shows for a brush preset node (`BPLv`): the preset's name,
/// else the brush's own name.
pub fn node_label(bpl: &Node) -> String {
    let (c, n) = (bpl.str_of("CAT").unwrap_or_default(), bpl.str_of("INM").unwrap_or_default());
    match find(c, n) {
        Some(i) => label(&BRUSH_PRESETS[i]),
        None => bpl.str_of("UNM").filter(|s| !s.is_empty()).unwrap_or(n.trim_start_matches("bn_")).to_owned(),
    }
}

/// A preset as a brush preset node (`BPLv`) of `diameter`, fields in Fireworks' order (dash
/// fields only for dashed brushes, which Fireworks MX doesn't have).
pub fn node(p: &BrushPreset, diameter: i32) -> Node {
    let i = |t: &str, v: i32| Node::int(t, v as i64);
    let mut c = vec![
        Node::string("CAT", p.category),
        Node::string("INM", p.name),
        Node::bool("RDO", false),
        i("BAN", p.angle),
        i("BAS", p.aspect),
        i("BDI", diameter.clamp(1, 1000)),
        i("BMM", p.max_count),
        i("BMS", p.min_size),
        i("BSE", p.softness),
        i("BSF", i32::from(p.bell)),
        i("BSH", i32::from(p.round)),
        i("BBL", 0),
        i("BBK", p.blackness),
        i("BCN", p.concentration),
        i("BEF", p.alpha_remap),
        i("BRT", if p.natural { 0 } else { 1 }),
        i("BFB", p.feedback),
        i("BFR", p.flow_rate),
        i("BNT", p.tip_count),
        i("BSP", p.spacing),
        i("BTB", p.texture_blend),
        i("BTE", p.texture_edge),
        i("BTS", p.tip_spacing),
        i("BSM", p.tip_spacing_mode),
        i("BCM", p.tip_coloring_mode),
        Node::bool("BIA", p.antialiased),
    ];
    if p.dash_count > 0 {
        c.push(i("NDI", p.dash_count));
        for (k, v) in p.dash_on.iter().enumerate() {
            c.push(i(&format!("DO{}", k + 1), *v));
        }
        for (k, v) in p.dash_off.iter().enumerate() {
            c.push(i(&format!("DF{}", k + 1), *v));
        }
    }
    for &(s, t, v) in p.sensitivities {
        let tag = String::from_utf8_lossy(&[b'S', s, t]).into_owned();
        c.push(i(&tag, v));
    }
    Node::vector("BPL", c)
}

/// The preset FireCraft uses for new strokes: Pencil, "1-Pixel Soft" (1-Pixel Anti-Aliased).
pub fn default_index() -> usize {
    find("bc_Pencil", "bn_1-Pixel Anti-Aliased").unwrap_or(0)
}
